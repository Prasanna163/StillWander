    private static final List<ShotPreset> PRESETS = java.util.stream.Stream.concat(
            BASE_PRESETS.stream(),
            ENVIRONMENT_PRESETS.stream()
    ).toList();

    private ShotLibrary() { }

    public static int size() {
        return PRESETS.size();
    }

    public static List<ShotPreset> matching(
            SubjectType subjectType,
            boolean wide,
            EnvironmentProfile profile
    ) {
        return PRESETS.stream()
                .filter(preset -> preset.subjectType() == subjectType)
                .filter(preset -> preset.wide() == wide)
                .filter(preset -> !profile.underground() || !preset.aerial())
                .filter(preset -> preset.environment().matches(profile))
                .toList();
    }
